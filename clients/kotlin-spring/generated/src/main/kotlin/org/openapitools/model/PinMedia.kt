/**
 * Pin media that can be an image, video, or a mix of both.
 * @param mediaType 
 * @param images 
 * @param coverImageUrl 
 * @param duration Duration (in miliseconds). Field maybe null after creation due to video processing time.
 * @param height Height (in pixels). Field maybe null after creation due to video processing time.
 * @param videoUrl Video url (720p).  **Note:** This field is limited and not available to all apps.
 * @param width Width (in pixels). Field maybe null after creation due to video processing time.
 * @param items 
 */
@JsonIgnoreProperties(
  value = ["media_type"], // ignore manually set media_type, it will be automatically generated by Jackson during serialization
  allowSetters = true // allows the media_type to be set during deserialization
)
@JsonTypeInfo(use = JsonTypeInfo.Id.NAME, include = JsonTypeInfo.As.PROPERTY, property = "media_type", visible = true)
@JsonSubTypes(
      JsonSubTypes.Type(value = PinMediaWithImage::class, name = "image"),
      JsonSubTypes.Type(value = PinMediaWithImages::class, name = "multiple_images"),
      JsonSubTypes.Type(value = PinMediaWithImageAndVideo::class, name = "multiple_mixed"),
      JsonSubTypes.Type(value = PinMediaWithVideos::class, name = "multiple_videos"),
      JsonSubTypes.Type(value = PinMediaWithVideo::class, name = "video")
)

interface PinMedia {
                @get:Schema(example = "null", requiredMode = Schema.RequiredMode.REQUIRED, description = "")
        val mediaType: PinMedia.MediaType

                @get:Schema(example = "null", description = "")
        val images: ImageSize? 

                @get:Schema(example = "null", description = "")
        val coverImageUrl: kotlin.String? 

                @get:Schema(example = "null", description = "Duration (in miliseconds). Field maybe null after creation due to video processing time.")
        val duration: java.math.BigDecimal? 

                @get:Schema(example = "null", description = "Height (in pixels). Field maybe null after creation due to video processing time.")
        val height: kotlin.Int? 

                @get:Schema(example = "null", description = "Video url (720p).  **Note:** This field is limited and not available to all apps.")
        val videoUrl: kotlin.String? 

                @get:Schema(example = "null", description = "Width (in pixels). Field maybe null after creation due to video processing time.")
        val width: kotlin.Int? 

                @get:Schema(example = "null", description = "")
        val items: kotlin.collections.List<PinMediaMetadata>? 


    /**
    * 
    * Values: multiple_mixed
    */
    enum class MediaType(@get:JsonValue val value: kotlin.String) {

        multiple_mixed("multiple_mixed");

        companion object {
            @JvmStatic
            @JsonCreator
            fun forValue(value: kotlin.String): MediaType {
                return values().firstOrNull{it -> it.value == value}
                    ?: throw IllegalArgumentException("Unexpected value '$value' for enum 'PinMedia'")
            }
        }
    }

}

