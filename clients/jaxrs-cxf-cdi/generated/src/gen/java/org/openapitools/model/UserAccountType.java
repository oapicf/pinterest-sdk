package org.openapitools.model;

import javax.validation.constraints.*;
import javax.validation.Valid;

import com.fasterxml.jackson.annotation.JsonCreator;
import com.fasterxml.jackson.annotation.JsonValue;
import com.fasterxml.jackson.annotation.JsonProperty;

public enum UserAccountType {

    @JsonProperty("PINNER") PINNER(String.valueOf("PINNER")), @JsonProperty("BUSINESS") BUSINESS(String.valueOf("BUSINESS"));


    private String value;

    UserAccountType(String v) {
        value = v;
    }

    public String value() {
        return value;
    }

    @Override
    public String toString() {
        return String.valueOf(value);
    }

    public static UserAccountType fromValue(String value) {
        for (UserAccountType b : UserAccountType.values()) {
            if (b.value.equals(value)) {
                return b;
            }
        }
        throw new IllegalArgumentException("Unexpected value '" + value + "'");
    }
}



