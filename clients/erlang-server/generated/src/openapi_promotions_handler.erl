-module(openapi_promotions_handler).
-moduledoc """
Exposes the following operation IDs:

- `POST` to `/ad_accounts/:ad_account_id/promotions`, OperationId: `promotions/create`:
Create promotions.
Create multiple new promotions.

- `DELETE` to `/ad_accounts/:ad_account_id/promotions/:promotion_id`, OperationId: `promotions/delete`:
Delete promotion by id.
Delete a promotion within Pinterest.

- `GET` to `/ad_accounts/:ad_account_id/promotions/:promotion_id`, OperationId: `promotions/get`:
Get promotion by id.
Get a promotion by its Pinterest-specific id. It must be associated with the provided ad account id.

- `GET` to `/ad_accounts/:ad_account_id/promotions`, OperationId: `promotions/list`:
Get promotions.
Gets all promotions associated with an ad account ID that can be applied to an ad group. Can be either internally-saved promotions or external promotions imported from a commerce integration.

- `PATCH` to `/ad_accounts/:ad_account_id/promotions`, OperationId: `promotions/update`:
Update promotions.
Update multiple promotions.

""".

-behaviour(cowboy_rest).

-include_lib("kernel/include/logger.hrl").

%% Cowboy REST callbacks
-export([init/2]).
-export([allowed_methods/2]).
-export([content_types_accepted/2]).
-export([content_types_provided/2]).
-export([delete_resource/2]).
-export([is_authorized/2]).
-export([valid_content_headers/2]).
-export([handle_type_accepted/2, handle_type_provided/2]).

-ignore_xref([handle_type_accepted/2, handle_type_provided/2]).

-export_type([class/0, operation_id/0]).

-type class() :: 'promotions'.

-type operation_id() ::
    'promotions/create' %% Create promotions
    | 'promotions/delete' %% Delete promotion by id
    | 'promotions/get' %% Get promotion by id
    | 'promotions/list' %% Get promotions
    | 'promotions/update'. %% Update promotions


-record(state,
        {operation_id :: operation_id(),
         accept_callback :: openapi_logic_handler:accept_callback(),
         provide_callback :: openapi_logic_handler:provide_callback(),
         api_key_callback :: openapi_logic_handler:api_key_callback(),
         context = #{} :: openapi_logic_handler:context()}).

-type state() :: #state{}.

-spec init(cowboy_req:req(), openapi_router:init_opts()) ->
    {cowboy_rest, cowboy_req:req(), state()}.
init(Req, {Operations, Module}) ->
    Method = cowboy_req:method(Req),
    OperationID = maps:get(Method, Operations, undefined),
    ?LOG_INFO(#{what => "Attempt to process operation",
                method => Method,
                operation_id => OperationID}),
    State = #state{operation_id = OperationID,
                   accept_callback = fun Module:accept_callback/4,
                   provide_callback = fun Module:provide_callback/4,
                   api_key_callback = fun Module:api_key_callback/2},
    {cowboy_rest, Req, State}.

-spec allowed_methods(cowboy_req:req(), state()) ->
    {[binary()], cowboy_req:req(), state()}.
allowed_methods(Req, #state{operation_id = 'promotions/create'} = State) ->
    {[<<"POST">>], Req, State};
allowed_methods(Req, #state{operation_id = 'promotions/delete'} = State) ->
    {[<<"DELETE">>], Req, State};
allowed_methods(Req, #state{operation_id = 'promotions/get'} = State) ->
    {[<<"GET">>], Req, State};
allowed_methods(Req, #state{operation_id = 'promotions/list'} = State) ->
    {[<<"GET">>], Req, State};
allowed_methods(Req, #state{operation_id = 'promotions/update'} = State) ->
    {[<<"PATCH">>], Req, State};
allowed_methods(Req, State) ->
    {[], Req, State}.

