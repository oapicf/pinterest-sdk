    {[<<"GET">>], Req, State};
allowed_methods(Req, #state{operation_id = 'catalogs/create'} = State) ->
    {[<<"POST">>], Req, State};
allowed_methods(Req, #state{operation_id = 'catalogs/list'} = State) ->
    {[<<"GET">>], Req, State};
allowed_methods(Req, State) ->
    {[], Req, State}.

