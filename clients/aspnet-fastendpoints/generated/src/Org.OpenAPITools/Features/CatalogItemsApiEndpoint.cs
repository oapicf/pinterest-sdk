/// <summary>
/// Get item batch status
/// </summary>

public class ItemsBatchGetEndpoint : FastEndpoints.Endpoint<ItemsBatchGetRequest, CatalogsItemsBatch>
{
    public override void Configure()
    {
        Get("/v5/catalogs/items/batch/{batch_id}");
        
        
        AllowAnonymous();
        
        Description(x =>
        {
            x.WithTags("catalog_items");
            FastEndpoints.RouteHandlerBuilderExtensions.ProducesProblemFE(x, 400);
            FastEndpoints.RouteHandlerBuilderExtensions.ProducesProblemFE(x, 401);
            FastEndpoints.RouteHandlerBuilderExtensions.ProducesProblemFE(x, 403);
            FastEndpoints.RouteHandlerBuilderExtensions.ProducesProblemFE(x, 404);
            FastEndpoints.RouteHandlerBuilderExtensions.ProducesProblemFE(x, 429);
            FastEndpoints.RouteHandlerBuilderExtensions.ProducesProblemFE(x, 0);
        });

        Summary(s => {
            s.Summary = "Get item batch status";
            s.RequestParam(r => r.BatchId, "Id of a catalogs items batch to fetch");
